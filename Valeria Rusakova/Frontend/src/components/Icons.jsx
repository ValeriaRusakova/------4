// Icons.jsx - small line icons drawn with SVG (no extra library needed).
// Every icon uses "currentColor", so it takes the text color of its button.
// aria-hidden="true": icons are decoration - the button's text/label explains the action.

function Icon({ children, size = 20, filled = false }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? "currentColor" : "none"}
      stroke={filled ? "none" : "currentColor"}
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {children}
    </svg>
  );
}

